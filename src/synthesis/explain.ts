/** Что значит настроение дня, чуть подробнее, чем в заголовке. */
export function moodAbout(mood: DayMood): string {
  switch (mood.title) {
    case 'Активный день':
      return 'Сил и решимости больше обычного. Хорошо браться за важное, начинать и действовать.';
    case 'Деятельный день':
      return 'Рабочий настрой: хорошо для дел, решений и встреч, но без гонки.';
    case 'Ровный день':
      return 'Ни подъёма, ни спада. Хорошо для обычных дел в своём темпе.';
    case 'Спокойный день':
      return 'Энергии меньше. Лучше завершать начатое, чем браться за новое.';
    default:
      return 'День для тишины и восстановления. Береги силы, не перегружай себя.';
  }
}

const MONTH_NAMES = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];
const pad = (n: number) => String(n).padStart(2, '0');

export interface PersonalStory {
  number: number;
  colorName: string;
  colorHex: string;
  /** Как получилось число: год, месяц, день. */
  steps: string[];
  about: string;
  favorable: string[];
  mindful: string[];
  tip: string;
  affirmation: string;
}

/** Личный день с расчётом и пояснением. birthday — чтобы показать «30.06» в расчёте (можно не передавать). */
export function personalStory(model: DayModel, content: Content, birthday?: { day: number; month: number } | null): PersonalStory | null {
  const p: PersonalNumbers | null = model.personal;
  if (!p) return null;
  const e = content.personal(p.day);
  const [y, m, d] = model.date.split('-').map(Number) as [number, number, number];
  const bd = birthday ? `${pad(birthday.day)}.${pad(birthday.month)}` : 'день и месяц рождения';
  const yearE = content.personal(p.year);
  const monthE = content.personal(p.month);
  return {
    number: p.day,
    colorName: e.color.name,
    colorHex: e.color.hex,
    steps: [
      `Личный год ${y}: ${p.year} (${bd} + ${y}, сложенные до одной цифры) — год, в котором главная тема «${yearE.theme}».`,
      `Личный месяц, ${MONTH_NAMES[m - 1]}: ${p.year} + ${m} → ${p.month}, тема месяца «${monthE.theme}».`,
      `Личный день, ${d}-е: ${p.month} + ${d} → ${p.day}.`,
    ],
    about: e.about,
    favorable: e.favorable,
    mindful: e.mindful,
    tip: e.tip,
    affirmation: e.affirmation,
  };
}

/** Убирает названия школ из текста для человека: «по авестийской традиции» → «по традиции». */
export const plainText = (s: string) => s.replace(/ по авестийской традиции/g, ' по традиции');
