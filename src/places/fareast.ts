const cache = new Map<number, string>();
function row(i: number): string {
  let r = cache.get(i);
  if (r === undefined) {
    r = ROWS[i]!.replace(/([A-Z.])(\d*)/g, (_m, ch: string, n: string) => ch.repeat(n ? Number(n) : 1));
    cache.set(i, r);
  }
  return r;
}

/** Пояс по сетке или null, если точка вне сетки или в клетке нет российского пояса. */
export function farEastZone(lat: number, lon: number): string | null {
  const i = Math.floor((lat - LAT0) / STEP);
  const j = Math.floor((lon - LON0) / STEP);
  if (i < 0 || i >= ROWS.length || j < 0) return null;
  const r = row(i);
  if (j >= r.length) return null;
  return Z[r[j]!] ?? null;
}
